from datetime import date, timedelta
from importlib import import_module

from django_valkey import get_valkey_connection

from django.apps import apps
from django.utils import timezone

from temba.flows.models import Flow, FlowActivityCount
from temba.tests import MigrationTest, cleanup


class BackfillFlowTalliesTest(MigrationTest):
    app = "flows"
    migrate_from = "0417_flowtally"
    migrate_to = "0418_backfill_flow_tallies"

    def setUpBeforeMigration(self, apps):
        self.today = timezone.now().date()
        self.yesterday = self.today - timedelta(days=1)
        self.expired = self.today - timedelta(days=366)

        self.flow1 = self.create_flow("Flow 1")
        self.flow2 = self.create_flow("Flow 2")
        self.flow3 = self.create_flow("Flow 3")

        def count(flow, scope, count, is_squashed=False):
            FlowActivityCount.objects.create(flow=flow, scope=scope, count=count, is_squashed=is_squashed)

        count(self.flow1, "segment:a:b", 10, is_squashed=True)
        count(self.flow1, "segment:a:b", 3)
        count(self.flow1, "segment:a:c", 4)
        count(self.flow1, "segment:c:d", 5)
        count(self.flow1, "segment:d:e", 0)
        count(self.flow1, "msgsin:hour:7", 6)
        count(self.flow1, f"msgsin:date:{self.yesterday}", 7)
        count(self.flow1, f"msgsin:date:{self.today}", 8)
        count(self.flow1, f"msgsin:date:{self.expired}", 9)
        count(self.flow1, "msgsin:dow:1", 10)
        count(self.flow1, "node:abc", 11)
        count(self.flow2, "segment:a:b", 12)
        count(self.flow3, "segment:a:b", 13)

        # tallies written since mailroom started writing them, some still buffered in Valkey, and one which is ahead
        # of its count because the counts never included it
        self.flow1.tallies.create(scope="segment:a:b", count=2)
        self.flow1.tallies.create(scope=f"msgsin:date:{self.today}", count=3)
        self.flow1.tallies.create(scope="segment:c:d", count=6)
        get_valkey_connection().hset(
            "{tallies}:live", mapping={f"F{self.flow1.id}|segment:a:b": 1, f"F{self.flow1.id}|segment:a:c": 4}
        )

        Flow.objects.filter(id=self.flow3.id).update(is_active=False)

    @cleanup(valkey=True)
    def test_migration(self):
        def expires(day: date) -> date:
            return day + timedelta(days=365)

        self.assertEqual(
            {
                ("segment:a:b", 12, None),  # 13 counted, of which 1 is still in Valkey
                ("segment:c:d", 6, None),
                ("msgsin:hour:7", 6, None),
                (f"msgsin:date:{self.yesterday}", 7, expires(self.yesterday)),
                (f"msgsin:date:{self.today}", 8, expires(self.today)),
            },
            set(self.flow1.tallies.values_list("scope", "count", "expires_on")),
        )
        self.assertEqual({("segment:a:b", 12)}, set(self.flow2.tallies.values_list("scope", "count")))
        self.assertFalse(self.flow3.tallies.exists())


class CompactSegmentTalliesTest(MigrationTest):
    app = "flows"
    migrate_from = "0418_backfill_flow_tallies"
    migrate_to = "0419_compact_segment_tallies"

    # exit, node and the compact scope generated by mailroom
    VECTORS = (
        (
            "42af6e19-53ef-4fd9-8232-f202a3ea022b",
            "1d4f25b2-c648-46cc-8116-be0ec6b6d34a",
            "segment:Qq9uGVPvT9mCMvICo-oCKx1PJbLGSEbMgRa-Dsa200o",
        ),
        (
            "2d7177e0-6bae-427f-9630-3823e2b8f1b2",
            "46681864-8389-4875-8b88-2f9fe241ea3f",
            "segment:LXF34GuuQn-WMDgj4rjxskZoGGSDiUh1i4gvn-JB6j8",
        ),
        (
            "00000000-0000-0000-0000-000000000000",
            "ffffffff-ffff-ffff-ffff-ffffffffffff",
            "segment:AAAAAAAAAAAAAAAAAAAAAP____________________8",
        ),
        (
            "fbfffbff-fbff-fbff-fbff-fbfffbfffbff",
            "3e3f3e3f-3e3f-3e3f-3e3f-3e3f3e3f3e3f",
            "segment:-__7__v_-__7__v_-__7_z4_Pj8-Pz4_Pj8-Pz4_Pj8",
        ),
    )

    def setUpBeforeMigration(self, apps):
        self.flow1 = self.create_flow("Flow 1")
        self.flow2 = self.create_flow("Flow 2")

        (exit1, node1, self.compact1), (exit2, node2, self.compact2), *_ = self.VECTORS

        # old only, old and compact for the same segment, already compact, an old zero and non-segment scopes
        self.flow1.tallies.create(scope=f"segment:{exit1}:{node1}", count=5)
        self.flow1.tallies.create(scope=f"segment:{exit2}:{node2}", count=3)
        self.flow1.tallies.create(scope=self.compact2, count=4)
        self.flow1.tallies.create(scope=f"segment:{exit2}:{node1}", count=0)
        self.flow1.tallies.create(scope="msgsin:hour:7", count=6)
        self.flow1.tallies.create(scope="node:abc", count=7)
        self.flow2.tallies.create(scope=self.compact1, count=8)

        # every vector in a flow of its own
        self.flow3 = self.create_flow("Flow 3")
        for exit_uuid, node_uuid, _ in self.VECTORS:
            self.flow3.tallies.create(scope=f"segment:{exit_uuid}:{node_uuid}", count=1)

    def test_migration(self):
        expected1 = {(self.compact1, 5), (self.compact2, 7), ("msgsin:hour:7", 6), ("node:abc", 7)}
        expected2 = {(self.compact1, 8)}
        expected3 = {(scope, 1) for _, _, scope in self.VECTORS}

        def assert_tallies():
            self.assertEqual(expected1, set(self.flow1.tallies.values_list("scope", "count")))
            self.assertEqual(expected2, set(self.flow2.tallies.values_list("scope", "count")))
            self.assertEqual(expected3, set(self.flow3.tallies.values_list("scope", "count")))

        assert_tallies()

        migration = import_module("temba.flows.migrations.0419_compact_segment_tallies")

        # running again is a no-op
        migration.compact_segment_tallies(apps, None)
        assert_tallies()

        # unless an old format total has since been flushed, in which case it's folded in too
        exit1, node1, _ = self.VECTORS[0]
        self.flow1.tallies.create(scope=f"segment:{exit1}:{node1}", count=2)
        migration.compact_segment_tallies(apps, None)

        expected1 = {(self.compact1, 7), (self.compact2, 7), ("msgsin:hour:7", 6), ("node:abc", 7)}
        assert_tallies()
